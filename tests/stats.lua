local Stats=dofile("SessionStats.lua")
local now,checks=0,0
local function eq(a,b,message)
    checks=checks+1; assert(a==b,(message or "Mismatch")..": "..tostring(a).." ~= "..tostring(b))
end
local stats=Stats.new(function() return now end)
local life,h={}, {Health=100}
stats:life(life,h)
stats:slaps(100,"counter")
stats:slaps(120,"counter")
eq(stats.SlapsEarned,0,"Paused growth excluded")
stats:observe({Alive=true,ArenaState="lobby",GloveName="Flash"},{TotalAttempts=2,TotalFailures=1})
eq(stats.PortalAttempts,0)
now=2; stats:setRunning(true)
stats:slaps(125,"counter")
eq(stats.SlapsEarned,5)
now=12
eq(stats:snapshot().ActiveSeconds,10)
eq(stats:snapshot().SlapsPerHour,1800)
stats:slaps(0,"counter"); stats:slaps(125,"counter")
eq(stats.SlapsEarned,5,"Counter reset and rebound never counted twice")
stats:slaps(130,"counter"); eq(stats.SlapsEarned,10)
stats:slaps(900,"replacement"); eq(stats.SlapsEarned,10,"New source rebased")
stats:slaps(nil,nil); eq(stats:snapshot().SlapsAvailable,false)
stats:slaps(950,"replacement"); eq(stats.SlapsEarned,10,"Missing interval not fabricated")
stats:slaps(952,"replacement"); eq(stats.SlapsEarned,12)
stats:observe({Alive=true,ArenaState="waiting"},{TotalAttempts=3,TotalFailures=1})
stats:observe({Alive=true,ArenaState="arena",GloveName="Default"},{TotalAttempts=3,TotalFailures=2})
eq(stats.ArenaEntries,1,"Lobby to arena after loading")
eq(stats.GloveChanges,1)
eq(stats.PortalAttempts,1)
eq(stats.PortalFailures,1)
stats:observe({Alive=true,ArenaState="arena"},{TotalAttempts=3,TotalFailures=2})
eq(stats.ArenaEntries,1)
h.Health=0; stats:death(life); stats:death(life)
stats:observe({Alive=false,ArenaState="waiting"},{TotalAttempts=3,TotalFailures=2})
eq(stats.Deaths,1,"Died event and polling deduplicated")
now=20; stats:setRunning(false)
eq(stats:snapshot().ActiveSeconds,18)
now=50; eq(stats:snapshot().ActiveSeconds,18,"Paused time excluded")
eq(stats:snapshot().SessionSeconds,50)
stats:slaps(960,"replacement")
local newLife,newH={}, {Health=100}
stats:life(newLife,newH); stats:observe({Alive=true,ArenaState="arena",GloveName="Default"})
eq(stats.ArenaEntries,1,"Spawning on arena not a portal entry")
newH.Health=0; stats:death(newLife); eq(stats.Deaths,1,"Paused death excluded")
stats:life({}, {Health=0}); stats:death(stats.Character)
eq(stats.Deaths,1,"Already-dead attachment excluded")
now=60; stats:setRunning(true); stats:slaps(963,"replacement")
eq(stats.SlapsEarned,15)
now=65; stats:setRunning(false); stats:setRunning(false)
eq(stats:snapshot().ActiveSeconds,23,"Repeated stop is idempotent")
for i=1,45 do stats:log("event "..i) end
eq(#stats.Logs,30,"Journal has bounded memory")
eq(stats.Logs[1].Text,"event 16")
stats:slaps(0/0,"replacement"); eq(stats:snapshot().SlapsAvailable,false)
stats:slaps(-1,"replacement"); eq(stats:snapshot().TotalSlaps,nil)
print("PASS: "..checks.." session statistics checks")
return checks
